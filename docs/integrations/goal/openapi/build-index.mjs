// Regenerates ../endpoints.md from ext-common.json — run after replacing the spec:
//   node docs/integrations/goal/openapi/build-index.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const spec = JSON.parse(readFileSync(join(here, 'ext-common.json'), 'utf8'))
const METHODS = ['get', 'post', 'put', 'patch', 'delete']

// "/ext/v1/schedulingScenarios/{code}/timetable" → "schedulingScenarios"
function domainOf(path) {
  if (/\/(new|end)\/transaction$/.test(path)) return 'transaction'
  if (path.includes('/vdv452/')) return 'vdv452'
  const parts = path.split('/').filter(Boolean)
  const i = parts[0] === 'ext' && /^v\d+$/.test(parts[1]) ? 2 : parts[0] === 'ext' || parts[0] === 'integration' ? 1 : 0
  return parts[i] ?? path
}

const clean = text => (text ?? '').replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim()

const byDomain = new Map()
for (const [path, item] of Object.entries(spec.paths)) {
  for (const method of METHODS) {
    const op = item[method]
    if (!op) continue
    const required = (op.parameters ?? []).filter(p => p.required && p.in !== 'header').map(p => p.name)
    const row = { method: method.toUpperCase(), path, summary: clean(op.summary || op.description), required }
    const domain = domainOf(path)
    byDomain.set(domain, [...(byDomain.get(domain) ?? []), row])
  }
}

const total = [...byDomain.values()].flat()
const reads = total.filter(r => r.method === 'GET').length
const lines = [
  '# Goal API — endpoint index',
  '',
  `> Generated by \`openapi/build-index.mjs\` from \`openapi/ext-common.json\` (${spec.info.title} ${spec.info.version}). Do not edit by hand.`,
  '> The curated map, with what nyx uses and what each call is for, is `api.md`.',
  '',
  `${total.length} operations: ${reads} GET and ${total.length - reads} that write or use POST to read. Required query/path parameters in the last column.`,
  '',
]
for (const domain of [...byDomain.keys()].sort((a, b) => a.localeCompare(b))) {
  lines.push(`## ${domain}`, '', '| Method | Path | Summary | Required |', '|---|---|---|---|')
  for (const r of byDomain.get(domain).sort((a, b) => a.path.localeCompare(b.path) || METHODS.indexOf(a.method.toLowerCase()) - METHODS.indexOf(b.method.toLowerCase()))) {
    lines.push(`| ${r.method} | \`${r.path}\` | ${r.summary} | ${r.required.map(p => `\`${p}\``).join(', ')} |`)
  }
  lines.push('')
}
writeFileSync(join(here, '..', 'endpoints.md'), lines.join('\n'))
console.log(`endpoints.md: ${total.length} operations in ${byDomain.size} domains`)
